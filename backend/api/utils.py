import io
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors
from django.core.mail import send_mail

def send_system_email(subject, message, recipient_email):
    """
    Sends transactional email to user. Falls back cleanly to console log if SMTP is not set up.
    """
    try:
        send_mail(
            subject=f"[Placement Portal] {subject}",
            message=message,
            from_email='placements@university.edu',
            recipient_list=[recipient_email],
            fail_silently=True
        )
        print(f"NOTIFICATION EMAIL SENT TO {recipient_email}: {subject}")
    except Exception as e:
        print(f"Mock Email Dispatch -> {recipient_email}: {subject} ({message[:50]}...)")

def generate_pdf_report(summary_data, student_records):
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=30, leftMargin=30, topMargin=30, bottomMargin=30)
    story = []

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontSize=20,
        leading=24,
        textColor=colors.HexColor('#1e293b'),
        alignment=1,
        spaceAfter=15
    )
    subtitle_style = ParagraphStyle(
        'DocSubTitle',
        parent=styles['Normal'],
        fontSize=11,
        leading=14,
        textColor=colors.HexColor('#64748b'),
        alignment=1,
        spaceAfter=20
    )
    h2_style = ParagraphStyle(
        'Heading2',
        parent=styles['Heading2'],
        fontSize=14,
        leading=18,
        textColor=colors.HexColor('#0f172a'),
        spaceAfter=10
    )

    story.append(Paragraph("University Campus Placement Analytics & Summary Report", title_style))
    story.append(Paragraph("Generated by AI-Powered Placement Management System", subtitle_style))
    story.append(Spacer(1, 10))

    # Executive Metrics Summary Table
    summary_table_data = [
        ["Total Registered Students", str(summary_data.get('total_students', 0)), "Highest Package Offered", f"₹{summary_data.get('highest_package', '0.0')} LPA"],
        ["Verified Students", str(summary_data.get('verified_students', 0)), "Average Salary Package", f"₹{summary_data.get('average_package', '0.0')} LPA"],
        ["Placed Candidates", str(summary_data.get('placed_students', 0)), "Lowest Package Offered", f"₹{summary_data.get('lowest_package', '0.0')} LPA"],
        ["Active Recruitment Drives", str(summary_data.get('active_drives', 0)), "Institutional Placement %", f"{summary_data.get('placement_pct', '0.0')}%"]
    ]

    t_summary = Table(summary_table_data, colWidths=[140, 100, 150, 110])
    t_summary.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#f8fafc')),
        ('TEXTCOLOR', (0,0), (-1,-1), colors.HexColor('#0f172a')),
        ('FONTNAME', (0,0), (-1,-1), 'Helvetica-Bold'),
        ('FONTSIZE', (0,0), (-1,-1), 9),
        ('ALIGN', (0,0), (-1,-1), 'LEFT'),
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#cbd5e1')),
        ('TOPPADDING', (0,0), (-1,-1), 6),
        ('BOTTOMPADDING', (0,0), (-1,-1), 6),
    ]))
    story.append(t_summary)
    story.append(Spacer(1, 20))

    # Student Placement Roster Table
    story.append(Paragraph("Placed Students Roster", h2_style))

    student_table_headers = ["Roll No", "Student Name", "Branch", "CGPA", "Company", "Job Role", "Package (LPA)"]
    student_table_rows = [student_table_headers]

    for s in student_records[:50]:  # limit 50 records for PDF layout
        student_table_rows.append([
            str(s.get('roll_no', '')),
            str(s.get('name', '')),
            str(s.get('branch', '')),
            str(s.get('cgpa', '')),
            str(s.get('company', '')),
            str(s.get('role', '')),
            f"₹{s.get('ctc', '0.0')}"
        ])

    t_students = Table(student_table_rows, colWidths=[70, 110, 50, 45, 95, 80, 70])
    t_students.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#1e40af')),
        ('TEXTCOLOR', (0,0), (-1,0), colors.white),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('FONTSIZE', (0,0), (-1,0), 9),
        ('ALIGN', (0,0), (-1,-1), 'CENTER'),
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#e2e8f0')),
        ('ROWBACKGROUNDS', (0,1), (-1,-1), [colors.white, colors.HexColor('#f1f5f9')]),
        ('TOPPADDING', (0,0), (-1,-1), 5),
        ('BOTTOMPADDING', (0,0), (-1,-1), 5),
    ]))
    story.append(t_students)

    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()

def generate_excel_report(summary_data, student_records):
    wb = openpyxl.Workbook()

    # Sheet 1: Executive Summary
    ws_summary = wb.active
    ws_summary.title = "Placement Summary"

    header_font = Font(name='Calibri', size=14, bold=True, color='FFFFFF')
    header_fill = PatternFill(start_color='1E3A8A', end_color='1E3A8A', fill_type='solid')

    ws_summary.merge_cells('A1:D1')
    ws_summary['A1'] = "UNIVERSITY CAMPUS PLACEMENT ANALYTICS"
    ws_summary['A1'].font = header_font
    ws_summary['A1'].fill = header_fill
    ws_summary['A1'].alignment = Alignment(horizontal='center', vertical='center')
    ws_summary.row_dimensions[1].height = 35

    summary_fields = [
        ("Total Registered Students", summary_data.get('total_students', 0)),
        ("Verified Students", summary_data.get('verified_students', 0)),
        ("Placed Candidates", summary_data.get('placed_students', 0)),
        ("Institutional Placement Rate", f"{summary_data.get('placement_pct', 0)}%"),
        ("Highest Package Offered", f"₹{summary_data.get('highest_package', 0)} LPA"),
        ("Average Package Offered", f"₹{summary_data.get('average_package', 0)} LPA"),
        ("Lowest Package Offered", f"₹{summary_data.get('lowest_package', 0)} LPA"),
        ("Total Recruitment Drives", summary_data.get('active_drives', 0)),
    ]

    row_idx = 3
    for label, val in summary_fields:
        ws_summary.cell(row=row_idx, column=1, value=label).font = Font(bold=True)
        ws_summary.cell(row=row_idx, column=2, value=val)
        row_idx += 1

    # Sheet 2: Placed Roster
    ws_students = wb.create_sheet(title="Student Roster")
    headers = ["Roll No", "Student Name", "Branch", "CGPA", "Backlogs", "Company Name", "Job Role", "Package (LPA)", "Status"]

    ws_students.append(headers)
    for col_num in range(1, len(headers) + 1):
        cell = ws_students.cell(row=1, column=col_num)
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill(start_color="1E40AF", end_color="1E40AF", fill_type="solid")
        cell.alignment = Alignment(horizontal="center")

    for s in student_records:
        ws_students.append([
            s.get('roll_no', ''),
            s.get('name', ''),
            s.get('branch', ''),
            s.get('cgpa', ''),
            s.get('backlogs', 0),
            s.get('company', 'Unplaced'),
            s.get('role', 'N/A'),
            s.get('ctc', 0.0),
            s.get('status', 'Applied')
        ])

    buffer = io.BytesIO()
    wb.save(buffer)
    buffer.seek(0)
    return buffer.getvalue()
